export function useLanguage() {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved !== "th" && saved !== "en") return;
    const frame = window.requestAnimationFrame(() => setLanguageState(saved));
    return () => window.cancelAnimationFrame(frame);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem(STORAGE_KEY, nextLanguage);
  };

  const t = (english: string) => language === "th" ? thaiTranslations[english] ?? english : english;

  return { language, setLanguage, t };
}

export function LanguageToggle({
  language,
  setLanguage,
}: {
  language: Language;
  setLanguage: (language: Language) => void;
}) {
  return (
    <div className="language-toggle" role="group" aria-label={language === "th" ? "เลือกภาษา" : "Choose language"}>
      <button type="button" className={language === "en" ? "active" : ""} onClick={() => setLanguage("en")} aria-pressed={language === "en"}>EN</button>
      <span aria-hidden="true">/</span>
      <button type="button" className={language === "th" ? "active" : ""} onClick={() => setLanguage("th")} aria-pressed={language === "th"}>TH</button>
    </div>
  );
}
